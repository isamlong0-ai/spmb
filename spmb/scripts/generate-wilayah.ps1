# Generate assets/js/wilayah-data.js dari API wilayah.id
# Jalankan dengan PowerShell: powershell -File scripts/generate-wilayah.ps1
$ErrorActionPreference = "Stop"
$base = "https://wilayah.id/api"
$provinsi = @("11","12","13","14","15","16","17","18","19","21","31","32","33","34","35","36","51","52","53","61","62","63","64","65","71","72","73","74","75","76","81","82","91","92","93","94","95","96")

$hasil = [ordered]@{}
foreach ($kodeProv in $provinsi) {
  Write-Host "Mengambil kabupaten provinsi $kodeProv..."
  try {
    $kab = (Invoke-RestMethod -Uri "$base/regencies/$kodeProv.json" -TimeoutSec 20).data
  } catch { $kab = @() }
  $entries = [ordered]@{ daftar = @(); kec = [ordered]@{}; desa = [ordered]@{} }
  foreach ($k in $kab) {
    $entries.daftar += ,@($k.code, $k.name)
    try {
      $kec = (Invoke-RestMethod -Uri "$base/districts/$($k.code).json" -TimeoutSec 20).data
      $arr = @()
      foreach ($d in $kec) {
        $arr += ,@($d.code, $d.name)
        if ($kodeProv -eq "61") {
          try {
            $des = (Invoke-RestMethod -Uri "$base/villages/$($d.code).json" -TimeoutSec 20).data
            $entries.desa[$d.code] = @($des | ForEach-Object { $_.name })
          } catch { $entries.desa[$d.code] = @() }
        }
      }
      $entries.kec[$k.code] = $arr
    } catch { $entries.kec[$k.code] = @() }
  }
  $hasil[$kodeProv] = $entries
}

$json = $hasil | ConvertTo-Json -Depth 12 -Compress
$out = "// Generated by scripts/generate-wilayah.ps1 - source: wilayah.id`n" +
       "export const WILAYAH_DATA = $json;`n"
$path = Join-Path $PSScriptRoot "..\assets\js\wilayah-data.js"
[System.IO.File]::WriteAllText($path, $out, [System.Text.UTF8Encoding]::new($false))
$ukuran = [math]::Round($out.Length / 1KB)
Write-Host "SELESAI: $path ($ukuran KB)"
